// Build-time script: extract cubie-level move transformations (EDGES + CORNERS
// orbits: permutation + orientationDelta) for the 18 HTM moves from cubing.js's
// authoritative cube3x3x3 KPuzzle definition, and also determine which edge
// indices are the "equator slice" (E-slice) edges (the 4 edges never touched by
// U or D moves). Output is a plain JS data file with no runtime dependency on
// cubing.js.

import { cube3x3x3 } from "cubing/puzzles";
import { Alg } from "cubing/alg";

const kp = await cube3x3x3.kpuzzle();

const FACES = ["U", "D", "L", "R", "F", "B"];
const SUFFIXES = ["", "2", "'"];

const moves = {};
for (const face of FACES) {
  for (const suffix of SUFFIXES) {
    const name = face + suffix;
    const alg = new Alg(name);
    const t = kp.algToTransformation(alg);
    moves[name] = {
      EDGES: {
        permutation: Array.from(t.transformationData.EDGES.permutation),
        orientationDelta: Array.from(t.transformationData.EDGES.orientationDelta),
      },
      CORNERS: {
        permutation: Array.from(t.transformationData.CORNERS.permutation),
        orientationDelta: Array.from(t.transformationData.CORNERS.orientationDelta),
      },
    };
  }
}

// Determine E-slice edge indices: edges fixed (permutation[idx] === idx) by
// both U and D.
const fixedByU = new Set(
  moves["U"].EDGES.permutation.map((v, i) => [v, i]).filter(([v, i]) => v === i).map(([, i]) => i),
);
const fixedByD = new Set(
  moves["D"].EDGES.permutation.map((v, i) => [v, i]).filter(([v, i]) => v === i).map(([, i]) => i),
);
const eSliceEdges = [...fixedByU].filter((i) => fixedByD.has(i)).sort((a, b) => a - b);

console.log("E-slice edge indices:", eSliceEdges);
if (eSliceEdges.length !== 4) {
  throw new Error("Expected exactly 4 E-slice edges, got " + eSliceEdges.length);
}

// Sanity check: identity checks (U * U * U * U == identity via U2*U2, U*U'==identity)
function combine(edgesA, cornersA, edgesB, cornersB) {
  const numO_e = 2, numO_c = 3;
  const ep = new Array(12), eo = new Array(12);
  for (let idx = 0; idx < 12; idx++) {
    ep[idx] = edgesA.permutation[edgesB.permutation[idx]];
    eo[idx] = (edgesA.orientationDelta[edgesB.permutation[idx]] + edgesB.orientationDelta[idx]) % numO_e;
  }
  const cp = new Array(8), co = new Array(8);
  for (let idx = 0; idx < 8; idx++) {
    cp[idx] = cornersA.permutation[cornersB.permutation[idx]];
    co[idx] = (cornersA.orientationDelta[cornersB.permutation[idx]] + cornersB.orientationDelta[idx]) % numO_c;
  }
  return { edges: { permutation: ep, orientationDelta: eo }, corners: { permutation: cp, orientationDelta: co } };
}

function isIdentity(edges, corners) {
  const idE = edges.permutation.every((v, i) => v === i) && edges.orientationDelta.every((v) => v === 0);
  const idC = corners.permutation.every((v, i) => v === i) && corners.orientationDelta.every((v) => v === 0);
  return idE && idC;
}

for (const face of FACES) {
  const q = moves[face];
  const h = moves[face + "2"];
  const inv = moves[face + "'"];
  const qq = combine(q.EDGES, q.CORNERS, q.EDGES, q.CORNERS);
  if (!isIdentity(combine(qq.edges, qq.corners, q.EDGES, q.CORNERS).edges, combine(qq.edges, qq.corners, q.EDGES, q.CORNERS).corners)) {
    // qqq should equal inv (quarter^3 == inverse), check separately below instead
  }
  const qqEq = JSON.stringify(qq.edges) === JSON.stringify(h.EDGES) && JSON.stringify(qq.corners) === JSON.stringify(h.CORNERS);
  const combined = combine(q.EDGES, q.CORNERS, inv.EDGES, inv.CORNERS);
  const invOk = isIdentity(combined.edges, combined.corners);
  console.log(face, "double==2x quarter:", qqEq, " quarter*inverse==identity:", invOk);
  if (!qqEq || !invOk) throw new Error("Move table sanity check failed for " + face);
}

const out = `// AUTO-GENERATED by gen/generate-tables.mjs — do not edit by hand.
// Cubie-level move transformations for the 18 HTM moves, extracted from
// cubing.js's cube3x3x3 KPuzzle definition.
//
// Convention (matches cubing.js): applying transformation T to a state S:
//   newPieces[idx]      = S.pieces[T.permutation[idx]]
//   newOrientation[idx] = (S.orientation[T.permutation[idx]] + T.orientationDelta[idx]) % numOrientations
//
// EDGES: 12 slots, orientation mod 2. Indices 8,9,10,11 are the equator
// (E-slice) slots -- the 4 edges never touched by a U or D move.
// CORNERS: 8 slots, orientation mod 3.

export const E_SLICE_EDGE_INDICES = ${JSON.stringify(eSliceEdges)};

export const MOVES = ${JSON.stringify(moves, null, 2)};
`;

const fs = await import("node:fs");
fs.writeFileSync(new URL("../moves-data.js", import.meta.url), out);
console.log("Wrote moves-data.js");
